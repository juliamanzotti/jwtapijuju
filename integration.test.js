const test = require('node:test');
const assert = require('node:assert/strict');
process.env.JWT_SECRET = 'teste-access-012345678901234567890123456789';
process.env.JWT_REFRESH_SECRET = 'teste-refresh-012345678901234567890123456789';
process.env.DB_FILE = ':memory:';
const bcrypt = require('bcrypt');
const db = require('../config/db');
const { app } = require('../index');
const { User, Loan, Book } = require('../models');

test('login, perfis, acervo, empréstimo, reserva e rotação', async () => {
  await db.sync({ force: true });
  await User.create({ name: 'Admin', username: 'admin', email: 'admin@teste.local', password: await bcrypt.hash('senha123', 10), isAdmin: true });
  const server = app.listen(0);
  const base = 'http://127.0.0.1:' + server.address().port + '/v1';
  let token = '';
  let cookie = '';
  async function request(path, method = 'GET', data, auth = true) {
    const response = await fetch(base + path, { method, headers: { ...(data ? { 'Content-Type': 'application/json' } : {}), ...(auth && token ? { Authorization: 'Bearer ' + token } : {}), ...(cookie ? { Cookie: cookie } : {}) }, body: data ? JSON.stringify(data) : undefined });
    const result = response.status === 204 ? null : await response.json();
    return { status: response.status, data: result, cookie: response.headers.get('set-cookie') };
  }
  try {
    assert.equal((await request('/auth/login', 'POST', { email: 'inexistente@teste.local', password: 'abc' }, false)).status, 401);
    const login = await request('/auth/login', 'POST', { email: 'admin@teste.local', password: 'senha123' }, false);
    assert.equal(login.status, 200);
    assert.ok(login.cookie.includes('HttpOnly'));
    assert.equal(login.data.refreshToken, undefined);
    token = login.data.accessToken;
    cookie = login.cookie.split(';')[0];
    const category = await request('/categories', 'POST', { name: 'Romance' });
    const author = await request('/authors', 'POST', { name: 'Ana Silva' });
    const reader = await request('/readers', 'POST', { name: 'Leitor', cpf: '12345678901' });
    assert.equal(category.status, 201);
    assert.equal(author.status, 201);
    assert.equal(reader.status, 201);
    const book = await request('/books', 'POST', { title: 'Livro Teste', isbn: '1234567890', totalCopies: 1, categoryId: category.data.id, authorIds: [author.data.id] });
    assert.equal(book.status, 201);
    const filtered = await request('/books?authorId=' + author.data.id);
    assert.equal(filtered.status, 200, JSON.stringify(filtered.data));
    assert.equal(filtered.data.total, 1);
    assert.equal((await request('/books?available=true')).data.total, 1);
    const loan = await request('/loans', 'POST', { bookId: book.data.id, readerId: reader.data.id });
    assert.equal(loan.status, 201);
    assert.equal((await Book.findByPk(book.data.id)).availableCopies, 0);
    assert.equal((await request('/loans', 'POST', { bookId: book.data.id, readerId: reader.data.id })).status, 409);
    const reservation = await request('/reservations', 'POST', { bookId: book.data.id, readerId: reader.data.id });
    assert.equal(reservation.status, 201);
    const otherReader = await request('/readers', 'POST', { name: 'Segundo Leitor', cpf: '12345678902' });
    assert.equal((await request('/reservations', 'POST', { bookId: book.data.id, readerId: otherReader.data.id })).status, 201);
    await Loan.update({ dueDate: new Date(Date.now() - 86400001) }, { where: { id: loan.data.id } });
    assert.equal((await request('/loans?status=ATRASADO')).data.total, 1);
    const returned = await request('/loans/' + loan.data.id + '/return', 'PATCH');
    assert.equal(returned.status, 200);
    assert.ok(Number(returned.data.fine) >= 1);
    assert.equal((await Book.findByPk(book.data.id)).availableCopies, 1);
    assert.equal((await request('/loans', 'POST', { bookId: book.data.id, readerId: otherReader.data.id })).status, 409);
    const reservedLoan = await request('/loans', 'POST', { bookId: book.data.id, readerId: reader.data.id });
    assert.equal(reservedLoan.status, 201);
    assert.equal((await request('/loans/' + reservedLoan.data.id + '/return', 'PATCH')).status, 200);
    assert.equal((await request('/loans', 'POST', { bookId: book.data.id, readerId: otherReader.data.id })).status, 201);
    const refreshed = await request('/auth/refresh', 'POST', undefined, false);
    assert.equal(refreshed.status, 200);
    const oldCookie = cookie;
    token = refreshed.data.accessToken;
    cookie = refreshed.cookie.split(';')[0];
    assert.equal((await request('/auth/refresh', 'POST', undefined, false)).status, 200);
    cookie = oldCookie;
    assert.equal((await request('/auth/refresh', 'POST', undefined, false)).status, 401);
    cookie = refreshed.cookie.split(';')[0];
    assert.equal((await request('/auth/refresh', 'POST', undefined, false)).status, 401);
    const staff = await request('/user', 'POST', { name: 'Atendente', username: 'staff', email: 'staff@teste.local', password: 'senha123' });
    assert.equal(staff.status, 201);
    const staffLogin = await request('/auth/login', 'POST', { email: 'staff@teste.local', password: 'senha123' }, false);
    token = staffLogin.data.accessToken;
    assert.equal((await request('/categories', 'POST', { name: 'Proibida' })).status, 403);
    assert.equal((await request('/books')).status, 200);
  } finally { server.close(); await db.close(); }
});
